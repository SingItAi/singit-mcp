// Shared helpers for the tool reference and the live check. No dependencies.
import { readFileSync } from "node:fs";

export const ENDPOINT = "https://app.singitai.app/mcp";

export const root = new URL("../", import.meta.url);
export const readJson = (rel) => JSON.parse(readFileSync(new URL(rel, root), "utf8"));

// How each tool is paid and which key scope it needs. Every tool in tools.json must be listed here;
// the offline test fails when the server adds a tool that this table does not know about yet.
const FREE_KEYLESS = { key: "No", scope: "none", network: "No payment" };
const ACCOUNT_READ = { key: "Yes (free, read-only)", scope: "account read, no paid-tool scope", network: "Account data" };
const PAID_SEARCH = { key: "Yes (paid)", scope: "search", network: "USDC on Base or Solana" };
const PAID_TOOLS = { key: "Yes (paid)", scope: "tools", network: "USDC, Base accounts only for now" };

export const TOOL_META = {
  get_price: FREE_KEYLESS,
  list_price_symbols: FREE_KEYLESS,
  list_models: FREE_KEYLESS,
  get_balance: ACCOUNT_READ,
  get_limits: ACCOUNT_READ,
  get_receipts: ACCOUNT_READ,
  web_search: PAID_SEARCH,
  read_page: PAID_SEARCH,
  get_weather: PAID_TOOLS,
  get_singit_risk_check: PAID_TOOLS,
  get_x_profile: PAID_TOOLS,
  get_crypto_news: PAID_TOOLS,
  get_hyperliquid_market: PAID_TOOLS,
  get_funding_rates: PAID_TOOLS,
  resolve_ens: PAID_TOOLS,
  get_token_price: PAID_TOOLS,
};

const firstSentence = (s) => {
  const m = s.replace(/\s+/g, " ").match(/^.*?[.!?](?=\s|$)/);
  return (m ? m[0] : s).replace(/\|/g, "\\|");
};

const params = (schema) => {
  const props = Object.keys(schema?.properties ?? {});
  if (props.length === 0) return "none";
  const req = new Set(schema.required ?? []);
  return props.map((p) => `\`${p}\`${req.has(p) ? " (required)" : ""}`).join(", ");
};

export function renderToolsDoc(snapshot) {
  const rows = snapshot.tools.map((t) => {
    const m = TOOL_META[t.name];
    if (!m) throw new Error(`tool ${t.name} has no entry in TOOL_META (scripts/lib.mjs)`);
    return `| \`${t.name}\` | ${firstSentence(t.description)} | ${params(t.inputSchema)} | ${m.key} | ${m.scope} | ${m.network} |`;
  });
  return `<!-- Generated by scripts/gen-tools-doc.mjs from tools.json. Do not edit by hand. -->
# Tool reference

${snapshot.tools.length} tools from the keyless \`tools/list\` response of \`${ENDPOINT}\`
(server \`${snapshot.serverInfo.name}\` "${snapshot.serverInfo.title}" ${snapshot.serverInfo.version}, protocol ${snapshot.protocolVersion}).
Snapshot taken ${snapshot.capturedAt}; \`npm run check:live\` compares it with the live server.

Paid tools are charged per call to the API key's own SingIt limits, and repeating a call charges again.
\`get_limits\` shows what the key has spent and what is left today.

| Tool | What it does | Parameters | Needs a key? | Key scope | Network |
|---|---|---|---|---|---|
${rows.join("\n")}
`;
}
